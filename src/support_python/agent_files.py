def get_digest_generator():
    """Dynamically load generate-agent-digest.py if present."""
    try:
        generator_path = _resolve_repo_root() / "scripts" / "generate-agent-digest.py"
        if generator_path.is_file():
            spec = importlib.util.spec_from_file_location("generate_agent_digest", generator_path)
            if spec and spec.loader:
                mod = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(mod)
                return mod
    except Exception:
        pass
    return None


def load_digest() -> str:
    digest_path = _resolve_digest_path()
    if not digest_path.is_file():
        return ""
    return digest_path.read_text(encoding="utf-8").strip()


def ensure_digest(action: str, logger: TeeLogger) -> str:
    """Load the digest from guidelines/agent-digest.md. If generate-agent-digest is available,
    verify that the digest is in sync with source guidelines. If out of sync:
    - on 'update': automatically regenerate guidelines/agent-digest.md and log the update.
    - on 'diff': log a warning that the digest file on disk is out of date.
    Returns the loaded digest string (or empty string if unavailable)."""
    digest_path = _resolve_digest_path()
    skills_dir = _resolve_skills_dir()
    generator = get_digest_generator()
    if generator is not None:
        try:
            expected = generator.build_digest()
            current = digest_path.read_text(encoding="utf-8") if digest_path.is_file() else ""
            if action == "update" and hasattr(generator, "build_skills"):
                try:
                    skills = generator.build_skills()
                    for skill_name, skill_content in skills.items():
                        skill_file = skills_dir / skill_name / "SKILL.md"
                        skill_file.parent.mkdir(parents=True, exist_ok=True)
                        if not skill_file.is_file() or skill_file.read_text(encoding="utf-8") != skill_content:
                            skill_file.write_text(skill_content, encoding="utf-8", newline="\n")
                except Exception as skill_err:
                    logger.log(f"Failed to synchronize derived skills: {skill_err}", level="DEBUG", origin=TOOL_NAME)

            if expected != current:
                if action == "update":
                    digest_path.write_text(expected, encoding="utf-8", newline="\n")
                    logger.log(
                        f"Regenerated {digest_path.name} from source guidelines",
                        origin=TOOL_NAME,
                    )
                    return expected.strip()
                elif action == "diff":
                    logger.log(
                        f"{digest_path.name} is out of date compared to source guidelines (run 'generate-agent-digest' or 'agent-files update' to synchronize)",
                        level="WARN",
                        origin=TOOL_NAME,
                    )
        except Exception as error:
            logger.log(f"Failed to check digest sources: {error}", level="DEBUG", origin=TOOL_NAME)

    return load_digest()


def build_guarded_block(digest: str, skills_catalog: str = "") -> str:
    content = digest.strip()
    if skills_catalog.strip():
        content = f"{content}\n\n{skills_catalog.strip()}"
    return f"{MARKER_BEGIN}\n\n{content}\n\n{MARKER_END}"


def apply_guarded_block(current_content: str, guarded_block: str) -> str:
    """Return current_content with its dev-guidelines guarded block replaced by guarded_block, or --
    if no guarded block exists yet -- guarded_block inserted at the very top, ahead of any existing
    (tool-specific/personal) content, which is otherwise left completely untouched."""
    has_begin = MARKER_BEGIN in current_content
    has_end = MARKER_END in current_content

    if has_begin and has_end:
        begin_idx = current_content.index(MARKER_BEGIN)
        end_idx = current_content.index(MARKER_END)
        if end_idx < begin_idx:
            raise ValueError("the dev-guidelines END marker appears before the BEGIN marker")
        new_content = current_content[:begin_idx] + guarded_block + current_content[end_idx + len(MARKER_END) :]
    elif not has_begin and not has_end:
        rest = current_content.strip()
        new_content = guarded_block if not rest else f"{guarded_block}\n\n{rest}"
    else:
        raise ValueError(
            "found only one of the dev-guidelines BEGIN/END markers -- the file may have been "
            "edited by hand into an inconsistent state; resolve manually before running update"
        )

    return new_content.strip() + "\n"


def print_tools(logger: TeeLogger | None = None) -> None:
    def executable_version(tool: Tool) -> tuple[str, str]:
        executable = resolve_command(tool)
        if executable is None:
            return "not found", "not found"

        try:
            result = subprocess.run([executable, "--version"], capture_output=True, text=True, timeout=10)
        except (OSError, subprocess.TimeoutExpired):
            return executable, "unknown"

        version = (result.stdout.strip() or result.stderr.strip() or "unknown").splitlines()[0]
        return executable, version

    rows = [
        (
            tool.name,
            tool.command,
            "available" if resolve_command(tool) else "unavailable",
            *executable_version(tool),
            str(tool.target_file),
            str(tool.skills_dir) if tool.skills_dir else "n/a",
        )
        for tool in TOOLS
    ]
    headers = ("Tool", "Command", "Status", "Executable", "Version", "Target", "Skills Target")
    widths = [max(len(header), *(len(row[index]) for row in rows)) for index, header in enumerate(headers)]

    lines = [
        "Configured AI tools",
        "-------------------",
        "  ".join(header.ljust(width) for header, width in zip(headers, widths)),
        "  ".join("-" * width for width in widths),
    ]
    for row in rows:
        lines.append("  ".join(value.ljust(width) for value, width in zip(row, widths)))

    for line in lines:
        if logger is not None:
            logger.emit(line)
        else:
            print(line)


