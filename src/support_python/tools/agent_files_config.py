DEFAULT_CONFIG_FILENAME = ".agent-files.json"
LEGACY_CONFIG_FILENAME = "agent-files.json"
DEFAULT_DIGEST_RELPATH = "agent-digest.md"
DEFAULT_SKILLS_RELPATH = "agent-skills"
DEFAULT_MARKER = "dev-guidelines"
DEFAULT_MARKER_BEGIN = (
    "<!-- BEGIN dev-guidelines (generated by agent-files sync -- do not edit by hand; edit the source digest instead) -->"
)
DEFAULT_MARKER_END = "<!-- END dev-guidelines -->"
DEFAULT_MANIFEST_SOURCE = "dev-guidelines"
DEFAULT_MANIFEST_NAME = ".dev-guidelines-skills.json"
DEFAULT_LEGACY_SKILL_NAMES: tuple[str, ...] = ("plan-task-usage", "ui-verification")

_ALLOWED_TOOL_KEYS = frozenset(
    {
        "name",
        "command",
        "target_file",
        "review_args",
        "fallback_paths",
        "skills_dir",
        "native_skill_discovery",
        "legacy_skills_dirs",
        "bootstrap_skill_names",
        "aliases",
    }
)


def default_review_args(prompt: str, target_filename: str, timeout: int) -> list[str]:
    """Return empty default CLI arguments for headless review when none are configured."""
    return []


class ToolRegistry:
    """Data-driven registry of AI coding tools supporting lookup and selection by name or alias."""

    def __init__(self, tools: Sequence[Any] | None = None) -> None:
        """Initialize the registry with the given tools, or the built-in defaults when None."""
        if tools is None:
            from support_python.tools.agent_files import TOOLS as default_tools

            tools = default_tools
        self._tools: list[Any] = list(tools)

    def register(self, tool: Any) -> None:
        """Add a tool to the registry or replace an existing entry matching its name or alias."""
        keys = {tool.name, *getattr(tool, "aliases", ())}
        for idx, existing in enumerate(self._tools):
            if keys & ({existing.name, *getattr(existing, "aliases", ())}):
                self._tools[idx] = tool
                return
        self._tools.append(tool)

    def get(self, name: str) -> Any | None:
        """Return the tool matching name or alias, or None if not registered."""
        for tool in self._tools:
            if name == tool.name or name in getattr(tool, "aliases", ()):
                return tool
        return None

    def list(self) -> list[Any]:
        """Return all registered tools in registration order."""
        return list(self._tools)

    def names(self) -> list[str]:
        """Return canonical names of all registered tools."""
        return [tool.name for tool in self._tools]

    def select(self, tool_names: Sequence[str]) -> list[Any]:
        """Return tools matching tool_names in registry order, or all tools when tool_names is empty."""
        if not tool_names:
            return list(self._tools)
        resolved = {self.get(name).name for name in tool_names if self.get(name) is not None}
        return [tool for tool in self._tools if tool.name in resolved]


@dataclass(frozen=True)
class AgentFilesConfig:
    """Resolved configuration for deterministic global agent-files and skills synchronization."""

    repo_root: Path
    digest_path: Path
    skills_dir: Path
    marker: str = DEFAULT_MARKER
    marker_begin: str = DEFAULT_MARKER_BEGIN
    marker_end: str = DEFAULT_MARKER_END
    #: Whether ``marker_begin`` was set explicitly; only then is it matched exactly instead of by :func:`begin_marker_pattern`.
    marker_begin_explicit: bool = False
    manifest_source: str = DEFAULT_MANIFEST_SOURCE
    manifest_name: str = DEFAULT_MANIFEST_NAME
    legacy_skill_names: tuple[str, ...] = DEFAULT_LEGACY_SKILL_NAMES
    tools: tuple[Any, ...] = ()


def begin_marker_pattern(marker: str) -> re.Pattern[str]:
    """Return the pattern matching any whole begin-marker line of ``marker``, whatever text follows the identifier.

    It recognizes guarded blocks written with an earlier begin-marker wording, such as the old dev-guidelines text.
    Only a parenthesized note may follow the identifier, so ``<!-- BEGIN {marker} personal -->`` is another marker.
    A line may start after a UTF-8 byte order mark at the start of the text.
    """
    return re.compile(
        rf"(?:^|(?<=\A\ufeff))<!-- BEGIN {re.escape(marker)}(?:[ \t]+\([^\r\n]*\))?[ \t]*-->(?=[ \t]*\r?$)",
        re.MULTILINE,
    )


def resolve_markers(
    marker: str = DEFAULT_MARKER,
    marker_begin: str | None = None,
    marker_end: str | None = None,
) -> tuple[str, str, str]:
    """Resolve marker identifier and guarded block begin/end marker lines."""
    if not isinstance(marker, str) or not marker.strip():
        raise ValueError("'marker' must be a non-empty string")
    clean = marker.strip()
    if marker_begin is not None and (not isinstance(marker_begin, str) or not marker_begin.strip()):
        raise ValueError("'marker_begin' must be a non-empty string")
    if marker_end is not None and (not isinstance(marker_end, str) or not marker_end.strip()):
        raise ValueError("'marker_end' must be a non-empty string")
    begin = (
        marker_begin.strip() if marker_begin else (DEFAULT_MARKER_BEGIN if clean == DEFAULT_MARKER else f"<!-- BEGIN {clean} -->")
    )
    end = marker_end.strip() if marker_end else (DEFAULT_MARKER_END if clean == DEFAULT_MARKER else f"<!-- END {clean} -->")
    return clean, begin, end


def _validate_str_list(value: Any, field_name: str) -> tuple[str, ...]:
    if not isinstance(value, list) or not all(isinstance(item, str) and item.strip() for item in value):
        raise ValueError(f"'{field_name}' must be a list of non-empty strings")
    return tuple(item.strip() for item in value)


def build_tool_from_dict(data: dict[str, Any], default_legacy_skills: tuple[str, ...] = (), logger: Any | None = None) -> Any:
    """Validate and construct a Tool instance from a JSON dictionary definition."""
    from support_python.tools.agent_files import Tool

    if isinstance(data, dict):
        data = normalize_config_keys(data, source=f"tool '{data.get('name')}'", logger=logger)
    if not isinstance(data, dict):
        raise ValueError("tool definition must be an object")
    if set(data.keys()) - _ALLOWED_TOOL_KEYS:
        raise ValueError(
            f"tool '{data.get('name')}' has unknown keys: {', '.join(kebab_keys(set(data.keys()) - _ALLOWED_TOOL_KEYS))}"
        )
    for req in ("name", "command", "target_file"):
        if not isinstance(data.get(req), str) or not data[req].strip():
            raise ValueError(f"tool definition requires non-empty string '{req}'")
    skills_raw = data.get("skills_dir")
    if skills_raw is not None and (not isinstance(skills_raw, str) or not skills_raw.strip()):
        raise ValueError("tool 'skills_dir' must be a non-empty string or null")
    native = data.get("native_skill_discovery", False)
    if not isinstance(native, bool):
        raise ValueError("tool 'native_skill_discovery' must be a boolean")
    raw_review = data.get("review_args")
    review_tpl = list(_validate_str_list(raw_review, "review_args")) if raw_review is not None else None
    review_fn: Callable[[str, str, int], list[str]] = (
        default_review_args
        if review_tpl is None
        else lambda p, t, to: [arg.format(prompt=p, target_file=t, timeout=to) for arg in review_tpl]
    )
    bootstrap = (
        _validate_str_list(data["bootstrap_skill_names"], "bootstrap_skill_names")
        if "bootstrap_skill_names" in data
        else default_legacy_skills
    )
    return Tool(
        name=data["name"].strip(),
        command=data["command"].strip(),
        target_file=Path(data["target_file"]).expanduser(),
        review_args=review_fn,
        fallback_paths=tuple(Path(p).expanduser() for p in _validate_str_list(data.get("fallback_paths", []), "fallback_paths")),
        skills_dir=Path(skills_raw).expanduser() if skills_raw else None,
        native_skill_discovery=native,
        legacy_skills_dirs=tuple(
            Path(p).expanduser() for p in _validate_str_list(data.get("legacy_skills_dirs", []), "legacy_skills_dirs")
        ),
        bootstrap_skill_names=bootstrap,
        aliases=_validate_str_list(data.get("aliases", []), "aliases"),
    )


def _resolve_path(base: Path, raw: str | Path) -> Path:
    candidate = Path(raw).expanduser()
    return candidate if candidate.is_absolute() else (base / candidate).resolve()


def _tools_by_name(raw: Any) -> Any:
    """Return the ``tools`` value as an object keyed by tool name, converting the list form."""
    if isinstance(raw, str) and raw.lstrip().startswith("["):
        raw = json.loads(raw)
    if not isinstance(raw, list):
        return raw
    named: dict[str, Any] = {}
    for entry in raw:
        name = entry.get("name") if isinstance(entry, dict) else None
        if not isinstance(name, str) or not name.strip():
            raise ValueError("tool definition requires non-empty string 'name'")
        named[name.strip()] = entry
    return named


